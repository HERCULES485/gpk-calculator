// Узлы модуля КАС (Кодекс административного судопроизводства РФ).
//
// ст. 298 — сроки подачи апелляционных жалобы, представления:
//   ч. 1 — общий месячный срок (APPEAL_GENERAL_KAS). Якорь — день принятия
//     решения суда в окончательной форме, то есть день составления
//     мотивированного решения (п. 6 Постановления Пленума ВС РФ от 11.06.2020
//     № 5).
//     ВНЕ ОБЪЁМА: сокращённые сроки ч. 2–6 ст. 298 — отдельные узлы; единица
//     дня у них зависит от категории дела (ч. 2 ст. 92 КАС РФ).
//     БЕЗ restoration-узла: восстановление срока предусмотрено (ст. 95, ч. 2
//     ст. 302 КАС РФ), но числового предельного срока для подачи заявления о
//     восстановлении в этих нормах нет — считать нечего.

import { computeSimpleTerm } from '../core/engine/term.js';

export const APPEAL_GENERAL_KAS = {
  id: 'appeal_general_kas',
  title: 'Апелляционная жалоба (КАС)',
  duration: { value: 1, unit: 'month' },
  anchor: { offset_start: 1 },
  weekend_shift: true,
  logic:
    'Месяц со дня принятия решения суда в окончательной форме (ч. 1 ст. 298 КАС РФ). ' +
    'Течение — со дня, следующего за днём составления мотивированного решения, а не со ' +
    'дня объявления резолютивной части (ч. 3 ст. 92, ст. 177 КАС РФ, п. 6 Постановления ' +
    'Пленума ВС РФ от 11.06.2020 № 5); истекает в соответствующее число следующего ' +
    'месяца (ч. 1 ст. 93 КАС РФ).',
  midnight_rule:
    'ч. 4 ст. 93 КАС РФ — процессуальное действие может быть совершено, а жалоба сдана ' +
    'в организацию почтовой связи, до 24:00 последнего дня срока.',
  norm_versions: [
    {
      id: 'current',
      from: null,
      to: null,
      anchor: { offset_start: 1 },
      norm: {
        primary: 'ч. 1 ст. 298 КАС РФ',
        calculation: ['ч. 3 ст. 92', 'ч. 1, 2 ст. 93 КАС РФ'],
        clarification: 'п. 6 Постановления Пленума ВС РФ от 11.06.2020 № 5',
      },
    },
  ],
};

/**
 * Срок подачи апелляционных жалобы, представления по ч. 1 ст. 298 КАС РФ.
 * @param {{decision_final_form_date_kas: string}} inputs — дата принятия решения
 *   суда в окончательной форме (дата составления мотивированного решения).
 * @returns {object} результат computeSimpleTerm (см. core/engine/term.js).
 */
export function computeAppealGeneralKas(inputs) {
  if (inputs?.decision_final_form_date_kas == null) {
    throw new Error(
      'Обязательна дата принятия решения суда в окончательной форме (decision_final_form_date_kas)',
    );
  }
  return computeSimpleTerm(APPEAL_GENERAL_KAS, inputs.decision_final_form_date_kas);
}

// --- Частная жалоба, представление прокурора на определение суда первой
// инстанции: общий срок (ч. 1 ст. 314 КАС РФ) -------------------------------
//
// Пятнадцать дней со дня вынесения определения судом первой инстанции, если
// иные сроки не установлены ст. 314. ПЕРВОЕ использование
// duration.unit: 'working_day' в домене kas/. Единицу назвал архитектор: срок
// исчисляется днями, а дела, к которым относится этот узел, не входят в
// перечень ч. 2 ст. 92 КАС РФ, поэтому включаются только рабочие дни. Механика
// — существующая ветка 'working_day' в core/engine/engine.js: первый день
// отсчёта — первый рабочий день после дня составления определения, считаются
// только рабочие дни, срок истекает в конце 15-го рабочего дня. Это совпадает
// с п. 6 Постановления Пленума ВС РФ от 11.06.2020 № 5. weekend_shift не
// указывается: движок не применяет его к working_day-срокам (последний день
// рабочий по построению).
//
// Якорь — одно поле ruling_final_form_date_kas: дата составления определения в
// окончательной форме. Ч. 1 ст. 314 говорит «со дня вынесения определения», а
// п. 6 Постановления Пленума № 5 уточняет, что течение срока на частную
// жалобу начинается со дня, следующего за днём составления мотивированного
// судебного акта. Если резолютивная часть определения объявлена, а полный
// текст составлен позже (не более чем через пять дней, п. 63 Постановления
// Пленума ВС РФ от 27.09.2016 № 36), вводится дата составления полного текста;
// если определение составлено в день вынесения — дата вынесения. Ветвления
// внутри функции нет: какую дату ввести, решает пользователь (тот же паттерн,
// что у APPEAL_GENERAL_KAS).
//
// НЕ ПРИМЕНЯЕТСЯ и ВНЕ ОБЪЁМА (каждое — отдельная задача архитектора):
//   - ч. 2–6 ст. 314: отдельные сроки в 5 и 10 дней для избирательных дел,
//     дел о помещении иностранного гражданина в специальное учреждение, об
//     административном надзоре, о недобровольной госпитализации и о
//     недобровольном психиатрическом освидетельствовании;
//   - дела из перечня ч. 2 ст. 92 КАС РФ (ч. 2 ст. 213, гл. 24, 28, 30, 31,
//     31.1): там дни календарные, а не рабочие, — этот узел к ним неприменим;
//   - дела упрощённого (письменного) производства: срок исчисляется со дня
//     получения копии определения (п. 76 Постановления Пленума ВС РФ от
//     27.09.2016 № 36).
//
// БЕЗ restoration-узла: восстановление срока на подачу частной жалобы
// предусмотрено (ст. 95 КАС РФ; п. 7 Постановления Пленума ВС РФ от
// 11.06.2020 № 5), но числового предельного срока для заявления о
// восстановлении ни в ст. 314, ни в ст. 95 нет — считать нечего.

