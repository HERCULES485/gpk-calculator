/**
 * Срок подачи апелляционных жалобы, представления по ч. 1 ст. 298 КАС РФ.
 * @param {{decision_final_form_date_kas: string}} inputs — дата принятия решения
 *   суда в окончательной форме (дата составления мотивированного решения).
 * @returns {object} результат computeSimpleTerm (см. core/engine/term.js).
 */
export function computeAppealGeneralKas(inputs) {
  if (inputs?.decision_final_form_date_kas == null) {
    throw new Error(
      'Обязательна дата принятия решения суда в окончательной форме (decision_final_form_date_kas)',
    );
  }
  return computeSimpleTerm(APPEAL_GENERAL_KAS, inputs.decision_final_form_date_kas);
}

