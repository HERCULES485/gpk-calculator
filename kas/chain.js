// --- Срок подачи кассационных жалобы, представления (ч. 2 ст. 318 КАС РФ) ----------
//
// Шесть месяцев со дня вступления судебного акта в законную силу при условии, что
// иные способы обжалования исчерпаны (ч. 2 ст. 318 КАС РФ). Кассации предшествует
// апелляция, поэтому акт, от которого идёт срок, — определение суда апелляционной
// инстанции: апелляционное определение вступает в законную силу со дня его принятия
// (ч. 5 ст. 311 КАС РФ), определение, вынесенное по частной жалобе, представлению
// прокурора, — со дня вынесения (ст. 317 КАС РФ). Течение срока начинается на
// следующий день после принятия такого определения (ч. 3 ст. 92 КАС РФ, п. 8
// Постановления Пленума ВС РФ от 09.07.2020 № 17).
//
// Срок единый: подача кассационных жалобы, представления в Судебную коллегию ВС РФ
// после обжалования в кассационный суд общей юрисдикции исчисление не начинает заново
// (п. 8 того же Постановления), поэтому отдельного узла для ВС РФ нет.
//
// Механика — существующая ветка 'month' в core/engine/engine.js, как у
// APPEAL_GENERAL_KAS и CLAIM_FILING_GENERAL_KAS: срок истекает в соответствующее число
// последнего месяца, а если такого числа нет — в последний день месяца (ч. 1 ст. 93 КАС
// РФ); если этот день нерабочий — переносится на ближайший рабочий (ч. 2 ст. 93 КАС РФ),
// поэтому weekend_shift: true, ветка 'month' этот флаг читает.
//
// Якорь — поле appellate_ruling_date_kas: дата принятия определения суда
// апелляционной инстанции (если апелляционных определений было несколько — дата
// последнего, п. 8 Постановления Пленума № 17). Это другой факт дела, чем
// decision_final_form_date_kas и ruling_final_form_date_kas, поэтому поле отдельное.
//
// Правило 24:00 и сдачи в организацию почтовой связи (ч. 4 ст. 93 КАС РФ, п. 9
// Постановления Пленума № 17) действует: ст. 318 в исключениях этой части не названа.
//
// ИСКЛЮЧАЕМЫЕ ПЕРИОДЫ (п. 9 Постановления Пленума № 17). Из шестимесячного срока
// исключаются срок составления мотивированного определения суда апелляционной
// инстанции, если составление откладывалось, и время рассмотрения кассационных
// жалобы, представления; время, в течение которого решался вопрос о возвращении
// жалобы по ст. 321 КАС РФ, не исключается. Оба входных поля необязательны: без них
// расчёт идентичен расчёту без исключений (результат не меняется и новых полей не
// получает).
//   - appellate_ruling_final_form_date_kas — дата составления мотивированного
//     апелляционного определения. Период: от даты принятия определения
//     (appellate_ruling_date_kas) до этой даты. Составление может быть отложено не
//     более чем на десять дней со дня окончания разбирательства (ч. 2 ст. 177 КАС РФ;
//     правила изготовления решения распространяются на апелляционное определение,
//     п. 42 Постановления Пленума ВС РФ от 11.06.2020 № 5); большая отсрочка узлом не
//     принимается (ошибка), а не усекается.
//   - cassation_consideration_periods_kas — массив периодов { start, end }: start —
//     дата поступления кассационных жалобы, представления в суд, end — дата
//     изготовления определения по результатам рассмотрения в полном объёме (именно
//     эти две даты п. 10 Постановления № 17 требует указывать в определениях
//     кассационных судов общей юрисдикции). Кассационных периодов может быть
//     несколько (кассационный суд общей юрисдикции, затем Судебная коллегия ВС РФ).
//     В список вносятся только периоды, подлежащие исключению: жалобу, возвращённую по
//     ст. 321 КАС РФ, вносить не нужно; чья именно жалоба рассматривалась, узел не
//     проверяет.
//
// АРХИТЕКТУРНЫЕ ДОПУЩЕНИЯ (нормы формул подсчёта не дают):
//   - число исключаемых дней периода = end − start, без +1 (как в
//     core/engine/exclusion.js): день начала события в период не входит, исключаются
//     дни, следующие за ним, по дату окончания включительно (ч. 3 ст. 92 КАС РФ — по
//     аналогии начала течения со следующего дня). Допущение консервативное: при
//     подсчёте с +1 исключалось бы на день больше, а дедлайн был бы позже;
//   - срок продлевается на сумму исключённых дней от последнего дня срока ДО переноса
//     на рабочий день, а перенос (ч. 2 ст. 93 КАС РФ) применяется один раз — к
//     итоговому дню: параметр extendFromRaw в core/engine/exclusion.js, withExclusions;
//   - исключаемый период не может начинаться раньше принятия апелляционного
//     определения и позже последнего дня срока (с учётом продления предшествующими
//     периодами): срок, который к началу периода уже истёк, продлить нельзя. Такие
//     данные — ошибка. Подача жалобы в день переноса срока на рабочий день (после
//     последнего календарного дня срока) тоже попадает под эту ошибку: как исключение
//     считать такой случай — отдельный вопрос архитектора;
//   - пересечение периодов — ошибка (core/engine/exclusion.js); стык встык
//     (end одного = start другого) допустим.
//
// НЕ УЧТЕНО и ВНЕ ОБЪЁМА (каждое — отдельная задача архитектора):
//   - акты, от которых срок идёт по п. 8 Постановления Пленума № 17, но не названы
