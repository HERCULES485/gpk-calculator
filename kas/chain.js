/**
 * Срок подачи кассационных жалобы, представления по ч. 2 ст. 318 КАС РФ (шесть
 * месяцев) с необязательным учётом периодов, исключаемых п. 9 Постановления Пленума
 * ВС РФ от 09.07.2020 № 17.
 * @param {{
 *   appellate_ruling_date_kas: string,
 *   appellate_ruling_final_form_date_kas?: string,
 *   cassation_consideration_periods_kas?: Array<{start: string, end: string}>,
 * }} inputs
 *   appellate_ruling_date_kas — дата принятия определения суда апелляционной инстанции
 *   (при нескольких апелляционных определениях — последнего);
 *   appellate_ruling_final_form_date_kas — дата составления мотивированного
 *   апелляционного определения, если составление откладывалось;
 *   cassation_consideration_periods_kas — периоды рассмотрения кассационных жалобы,
 *   представления: start — дата поступления жалобы, end — дата изготовления
 *   определения в полном объёме.
 * @returns {object} результат computeSimpleTerm (см. core/engine/term.js); если
 *   исключаемые дни есть — результат withExclusions (core/engine/exclusion.js).
 * @throws {Error} при отсутствии обязательной даты и при недопустимых периодах.
 */
export function computeCassationGeneralKas(inputs) {
  if (inputs?.appellate_ruling_date_kas == null) {
    throw new Error(
      'Обязательна дата принятия определения суда апелляционной инстанции (appellate_ruling_date_kas)',
    );
  }
  const term = computeSimpleTerm(CASSATION_GENERAL_KAS, inputs.appellate_ruling_date_kas);
  if (term == null) return null;

  // Период составления мотивированного определения: от принятия определения до
  // даты его составления.
  const finalFormInput = inputs.appellate_ruling_final_form_date_kas;
  let drafting = [];
  if (finalFormInput != null && finalFormInput !== '') {
    const finalForm = toISO(finalFormInput);
    if (finalForm == null) {
      throw new Error(
        'Некорректная дата составления мотивированного апелляционного определения (appellate_ruling_final_form_date_kas)',
      );
    }
    if (finalForm < term.anchor) {
      throw new Error(
        'Дата составления мотивированного апелляционного определения (appellate_ruling_final_form_date_kas) раньше даты его принятия',
      );
    }
    const latest = toISODate(addDays(term.anchor, MAX_DRAFTING_DAYS_KAS));
    if (finalForm > latest) {
      throw new Error(
        'Составление мотивированного апелляционного определения может быть отложено не более ' +
          'чем на десять дней (ч. 2 ст. 177 КАС РФ, п. 42 Постановления Пленума ВС РФ от ' +
          `11.06.2020 № 5); превышение узлом не учитывается — укажите дату не позже ${latest} ` +
          '(appellate_ruling_final_form_date_kas)',
      );
    }
    drafting = exclusionEvents([{ start: term.anchor, end: finalForm }], {
      fixedType: DRAFTING_EXCLUSION_TYPE_KAS,
    });
  }

  // Периоды рассмотрения кассационных жалобы, представления.
  const periodsInput = inputs.cassation_consideration_periods_kas;
  if (periodsInput != null && !Array.isArray(periodsInput)) {
    throw new Error(
      'cassation_consideration_periods_kas должен быть массивом периодов { start, end }',
    );
  }
  const consideration = exclusionEvents(periodsInput, {
    fixedType: CONSIDERATION_EXCLUSION_TYPE_KAS,
  });
  for (const event of consideration) {
    if (event.ignored) {
      throw new Error(
        'Период рассмотрения кассационных жалобы, представления не может быть учтён: ' +
          `${CONSIDERATION_IGNORED_REASON_KAS[event.ignored_reason]} (cassation_consideration_periods_kas)`,
      );
    }
    if (event.start < term.anchor) {
      throw new Error(
        `Период рассмотрения кассационных жалобы, представления ${event.start}–${event.end} ` +
          `начинается раньше даты принятия апелляционного определения ${term.anchor} ` +
          '(cassation_consideration_periods_kas)',
      );
    }
  }

  // Пересечение периодов — ошибка (core); исключённых дней нет — срок не меняется.
  const excludedDays = totalExcludedDays([drafting, consideration]);
  if (excludedDays === 0) return term;

  // Период не может начинаться после последнего дня срока с учётом продления
  // предшествующими периодами. Период составления начинается в день принятия
  // определения, периоды рассмотрения начинаются не раньше него и идут по возрастанию
  // даты начала, поэтому порядок [drafting, consideration] уже хронологический.
  let lastDay = term.raw_deadline;
  for (const event of [...drafting, ...consideration]) {
    if (event.start > lastDay) {
      throw new Error(
        `Период рассмотрения кассационных жалобы, представления ${event.start}–${event.end} ` +
          `начинается после окончания шестимесячного срока (${lastDay}); расчёт для такого ` +
          'случая, в том числе при подаче жалобы в день переноса срока на рабочий день, не ' +
          'поддерживается (cassation_consideration_periods_kas)',
      );
    }
    lastDay = toISODate(addDays(lastDay, event.days));
  }

  const parts = [];
  if (drafting.some((e) => e.days > 0)) {
    parts.push('время составления мотивированного апелляционного определения');
  }
  if (consideration.some((e) => e.days > 0)) {
    parts.push('время рассмотрения кассационных жалобы, представления');
  }
  return withExclusions(term, [drafting, consideration], {
    norm: 'п. 9 Постановления Пленума ВС РФ от 09.07.2020 № 17',
    logic:
      `Из шестимесячного срока исключено: ${parts.join('; ')}. Срок продлён на число ` +
      'исключённых дней от последнего дня срока до переноса; итоговый последний день при ' +
      'необходимости перенесён на ближайший рабочий (ч. 2 ст. 93 КАС РФ).',
    extendFromRaw: true,
  });
}

// --- Восстановление срока кассации: двенадцатимесячный потолок (ч. 3 ст. 318 КАС РФ) ---
//
// Ч. 3 ст. 318: пропущенный срок подачи кассационных жалобы, представления «может быть
// восстановлен судом кассационной инстанции только в случае, если обстоятельства,
// послужившие причиной его пропуска, имели место в период не позднее двенадцати месяцев
// со дня вступления обжалуемого судебного акта в законную силу» (или если заявление подано
// лицом, не участвовавшим в деле, — см. «НЕ УЧТЕНО» ниже). Числового срока для подачи самого
// заявления о восстановлении норма не содержит (ст. 95 КАС РФ его тоже не называет), поэтому
// узла-срока здесь нет: функция только проверяет, укладывается ли дата обстоятельства в
// двенадцать месяцев. Результат — не карточка срока и не проходит через computeSimpleTerm.
//
// Архитектурные допущения (решены архитектором, не исполнителем):
//   - механика — checkRestorationOneYearCap из core/engine/restoration.js (потолок
//     «соответствующее число через двенадцать месяцев», границы включительно). Счёт совпадает
//     с ч. 3 ст. 92 и ч. 1 ст. 93 КАС РФ: течение начинается на следующий день, срок
//     истекает в соответствующее число последнего месяца, а если такого числа нет — в
//     последний день месяца;
//   - на рабочий день последний день периода НЕ переносится: ч. 2 ст. 93 КАС РФ переносит
//     «последний день процессуального срока», а двенадцать месяцев ограничивают время
//     обстоятельств, а не срок совершения процессуального действия;
//   - день вступления в силу — день принятия апелляционного определения (ч. 5 ст. 311 КАС РФ),
//     то есть та же appellate_ruling_date_kas, что и якорь cassation_general_kas; дата
//     составления мотивированного определения на потолок не влияет;
//   - нижняя граница нормой не задана: обстоятельство, датированное раньше вступления
//     определения в силу, верхнюю границу не нарушает и не отвергается;
//   - уважительность причины пропуска оценивает суд (ст. 95 КАС РФ) — не вычисляется.
//
// НЕ УЧТЕНО и ВНЕ ОБЪЁМА (каждое — отдельная задача архитектора):
//   - второе основание ч. 3 ст. 318 — заявление лица, не участвовавшего в деле, о правах и
//     об обязанностях которого суд принял судебный акт, «со дня, когда это лицо узнало или
//     должно было узнать о нарушении его прав»: норма не называет, какой период
//     отсчитывается от этого дня, а п. 11 Постановления Пленума ВС РФ от 09.07.2020 № 17
//     повторяет текст без разъяснения. within_cap: false для такого лица не означает, что
//     восстановление невозможно;
