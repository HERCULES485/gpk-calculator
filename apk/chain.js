/**
 * Срок подачи апелляционной жалобы по ч. 1 ст. 259 АПК РФ.
 * @param {{decision_full_text_date: string}} inputs — дата изготовления решения
 *   арбитражного суда первой инстанции в полном объёме.
 * @returns {object} результат computeSimpleTerm (см. core/engine/term.js).
 */
export function computeAppealGeneralApk(inputs) {
  if (inputs?.decision_full_text_date == null) {
    throw new Error(
      'Обязательна дата изготовления решения в полном объёме (decision_full_text_date)',
    );
  }
  return computeSimpleTerm(APPEAL_GENERAL_APK, inputs.decision_full_text_date);
}

// --- Восстановление срока (ч. 2 ст. 259 АПК РФ) ------------------------------
//
// Норма регулирует две разные вещи, и узел считает только вторую:
//   (а) уважительность причин пропуска — судебное усмотрение, оценивается по
//       обстоятельствам дела (п. 15 Постановления Пленума ВС РФ от 30.06.2020
//       № 12). Не вычисляется и здесь не кодируется: это не про даты;
//   (б) формальный предельный срок подачи самого ходатайства — шесть месяцев
//       от точки отсчёта, зависящей от категории субъекта. Это и считается.
//
// Три категории субъектов с разными якорями:
//   participating_duly_notified — участвовавшее в деле лицо, надлежаще
//     извещённое о разбирательстве в суде первой инстанции; шесть месяцев со
//     дня принятия решения (ч. 2 ст. 259, первая часть; п. 14 Постановления
//     № 12, первый абзац: по истечении этих шести месяцев восстановление не
//     производится);
//   article_42_person — лицо, не участвовавшее в деле, о правах и об
//     обязанностях которого принят судебный акт (ст. 42 АПК РФ); шесть месяцев
//     со дня, когда лицо узнало или должно было узнать о нарушении своих прав
//     (ч. 2 ст. 259, вторая часть);
//   participating_improperly_notified — участвовавшее в деле лицо, не
//     принимавшее участия в разбирательстве из-за ненадлежащего извещения о
//     времени и месте заседания; та же точка отсчёта, что и у ст. 42, но иное
//     правовое основание — эта категория названа не в тексте ч. 2 ст. 259, а в
//     п. 14 Постановления № 12 (второй абзац). Механика совпадает, основания
//     разные — не отождествлять.
//
// Арифметика у всех трёх одна: шесть месяцев с переносом последнего дня на
// рабочий (ч. 4 ст. 113, ч. 2, 4 ст. 114 АПК РФ — общие правила для сроков,
// исчисляемых месяцами; исключений из них ч. 2 ст. 259 не устанавливает).

