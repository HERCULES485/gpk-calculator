const RESTORATION_SUBJECT_CATEGORIES = new Set([
  'participating_duly_notified',
  'article_42_person',
  'participating_improperly_notified',
]);

/**
 * Предельный срок подачи ходатайства о восстановлении срока апелляционного
 * обжалования по ч. 2 ст. 259 АПК РФ. Не оценивает уважительность причин
 * пропуска (это решает суд) — только формальный крайний срок ходатайства.
 *
 * @param {{
 *   subject_category: 'participating_duly_notified' | 'article_42_person' | 'participating_improperly_notified',
 *   decision_full_text_date?: string,
 *   learned_of_violation_date?: string,
 * }} inputs
 */
export function computeAppealGeneralApkRestoration(inputs) {
  const category = inputs?.subject_category;
  if (!RESTORATION_SUBJECT_CATEGORIES.has(category)) {
    throw new Error(
      `subject_category должен быть одним из: ${[...RESTORATION_SUBJECT_CATEGORIES].join(', ')}`,
    );
  }

  let anchorInput;
  if (category === 'participating_duly_notified') {
    anchorInput = inputs.decision_full_text_date;
    if (anchorInput == null) {
      throw new Error(
        'Для категории participating_duly_notified обязательна decision_full_text_date',
      );
    }
  } else {
    anchorInput = inputs.learned_of_violation_date;
    if (anchorInput == null) {
      throw new Error(`Для категории ${category} обязательна learned_of_violation_date`);
    }
  }

  const calc = computeSimpleTerm(APPEAL_GENERAL_APK_RESTORATION, anchorInput);
  return { ...calc, subject_category: category };
}

// --- Вступление решения в законную силу (ч. 1 ст. 180 АПК РФ) ----------------
//
// Первый узел модуля, который НЕ является сроком: это момент смены статуса
// решения, а не отрезок времени на совершение действия. Отсюда две особенности,
// отличающие его от узлов ст. 259:
//
//   1. У него нет ни duration, ни anchor, ни weekend_shift — эти поля описывают
//      «длительность от точки отсчёта», а здесь такой конструкции нет по смыслу
//      нормы. Декоративные поля не заводятся: они бы вводили в заблуждение
//      относительно контракта узла и подталкивали прогнать его через
//      computeSimpleTerm, для которого он не предназначен.
//   2. Правило переноса последнего дня на рабочий (ч. 4 ст. 114 АПК РФ) к самой
//      дате вступления в силу НЕ применяется. Оно регулирует последний день
//      процессуального СРОКА, а срок на апелляцию (вместе со своим уже
//      перенесённым последним днём) полностью вычислен внутри
//      appeal_general_apk. Вступление в силу — следующий календарный день после
//      готового результата, поэтому дата может прийтись и на выходной. Второй
//      раз перенос не применяется. Так же устроен и одноимённый узел
//      ГПК-домена: там тестом закреплено вступление в силу в субботу.
//
// Две ветки нормы:
//   жалоба не подана — день, следующий за последним днём месячного срока на
//     апелляцию (первое предложение ч. 1 ст. 180);
//   жалоба подана, решение не отменено и не изменено — день принятия
//     постановления апелляционной инстанции (второе предложение). Эта дата не
//     вычисляется: постановление принимает другой суд по итогам рассмотрения
//     жалобы, для калькулятора это внешний факт.
//
// ВНЕ МОДЕЛИ: случай «жалоба подана, решение отменено или изменено». Тогда в
// силу вступает не исходное решение, а новое постановление апелляции, и знать
// нужно исход рассмотрения, а не только его дату; такого факта в apk/ пока нет
// ни в одном узле. Поэтому исход требуется подтвердить явно (appeal_outcome:
// 'affirmed'), а без подтверждения узел бросает ошибку, а не угадывает.

export const ENTRY_INTO_FORCE_APK = {
  id: 'entry_into_force_apk',
  title: 'Вступление решения в законную силу (АПК)',
  norm: {
    primary: 'ч. 1 ст. 180 АПК РФ',
  },
};

/**
 * Дата вступления решения арбитражного суда первой инстанции в законную силу
 * (ч. 1 ст. 180 АПК РФ). Две ветки:
 *  - жалоба не подана: день, следующий за (уже перенесённым) последним днём
 *    срока на апелляцию (см. appeal_general_apk);
 *  - жалоба подана и решение оставлено без изменения: дата постановления
 *    апелляционной инстанции, передаётся как есть.
 * Случай "жалоба подана, решение отменено/изменено" не поддерживается —
 * бросает ошибку, если исход явно не подтверждён как "без изменения".
 *
 * @param {{
 *   appeal_filed: boolean,
 *   decision_full_text_date?: string,
 *   appellate_ruling_date?: string,
 *   appeal_outcome?: 'affirmed',
 * }} inputs
 */
export function computeEntryIntoForceApk(inputs) {
  if (inputs?.appeal_filed == null) {
    throw new Error('Обязательно явное appeal_filed (true/false)');
  }

  if (inputs.appeal_filed === false) {
    if (inputs.decision_full_text_date == null) {
      throw new Error('Для appeal_filed=false обязательна decision_full_text_date');
    }
    const appeal = computeAppealGeneralApk({
      decision_full_text_date: inputs.decision_full_text_date,
    });
    // День, следующий за уже перенесённым дедлайном апелляции — без
    // повторного применения переноса через нерабочий день (см. выше).
    const date = toISO(addDays(appeal.deadline, 1));
    return { id: ENTRY_INTO_FORCE_APK.id, date, based_on: 'appeal_general_apk' };
  }

  if (inputs.appeal_outcome !== 'affirmed') {
    throw new Error(
      'Случай "жалоба подана, решение отменено/изменено" не поддерживается ' +
        '(appeal_outcome должен быть "affirmed" при appeal_filed=true)',
    );
  }
  if (inputs.appellate_ruling_date == null) {
    throw new Error(
      'Для appeal_filed=true и appeal_outcome="affirmed" обязательна appellate_ruling_date',
    );
  }
  return {
    id: ENTRY_INTO_FORCE_APK.id,
    date: inputs.appellate_ruling_date,
    based_on: 'appellate_ruling_date',
  };
}

