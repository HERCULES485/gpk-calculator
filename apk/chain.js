// Апелляционная жалоба по АПК РФ (ч. 1 ст. 259) — задача 1b аудита apk/259.
//
// Объём сознательно сужен: только ч. 1 ст. 259 (общий месячный срок).
// Восстановление пропущенного срока (ч. 2 ст. 259) — отдельная задача, здесь
// не реализовано и намеренно не включено в объект узла (нет restoration_norm).
// Регистрация узла в UI-реестре ситуаций и в .ics-реестре — тоже отдельная
// задача (нет поля ics — оно сейчас нерабочее, ни один реестр apk/ не сканирует
// экспорты этого модуля).
//
// Домен АПК не переиспользует ГПК-поле reasoned_decision_date — имя входного
// поля должно однозначно указывать на АПК-семантику.

import { computeSimpleTerm } from '../core/engine/term.js';

export const APPEAL_GENERAL_APK = {
  id: 'appeal_general_apk',
  title: 'Апелляционная жалоба (АПК)',
  duration: { value: 1, unit: 'month' },
  anchor: { offset_start: 1 },
  weekend_shift: true,
  logic:
    'Месяц со дня изготовления решения арбитражного суда первой инстанции в полном ' +
    'объёме (не со дня направления копии решения сторонам — п. 12 Постановления Пленума ' +
    'ВС РФ от 30.06.2020 № 12). Течение — со дня, следующего за днём изготовления ' +
    'решения в полном объёме (ч. 4 ст. 113 АПК РФ); истекает в соответствующее число ' +
    'следующего месяца (ч. 2 ст. 114 АПК РФ).',
  midnight_rule:
    'ч. 5, 6 ст. 114 АПК РФ — процессуальное действие может быть совершено, а жалоба ' +
    'сдана на почту, до 24:00 последнего дня срока.',
  norm_versions: [
    {
      id: 'current',
      from: null,
      to: null,
      anchor: { offset_start: 1 },
      norm: {
        primary: 'ч. 1 ст. 259 АПК РФ',
        calculation: ['ч. 4 ст. 113', 'ч. 2, 4 ст. 114 АПК РФ'],
        clarification: 'п. 12 Постановления Пленума ВС РФ от 30.06.2020 № 12',
      },
    },
  ],
};

/**
 * Срок подачи апелляционной жалобы по ч. 1 ст. 259 АПК РФ.
 * @param {{decision_full_text_date: string}} inputs — дата изготовления решения
 *   арбитражного суда первой инстанции в полном объёме.
 * @returns {object} результат computeSimpleTerm (см. core/engine/term.js).
 */
export function computeAppealGeneralApk(inputs) {
  if (inputs?.decision_full_text_date == null) {
    throw new Error(
      'Обязательна дата изготовления решения в полном объёме (decision_full_text_date)',
    );
  }
  return computeSimpleTerm(APPEAL_GENERAL_APK, inputs.decision_full_text_date);
}
