//
// ст. 188 — сроки:
//   ч. 3 — частная жалоба на определение суда первой инстанции
//     (PRIVATE_COMPLAINT_FIRST_INSTANCE_APK). Первый узел новой категории —
//     обжалование определений, а не решений; якорь считается от дня
//     вынесения определения буквально, без оговорки об изготовлении в полном
//     объёме (в отличие от APPEAL_GENERAL_APK).
//   ч. 4 — частная жалоба на определение суда апелляционной инстанции
//     (PRIVATE_COMPLAINT_APPELLATE_APK). Та же механика, что у ч. 3.
//   ч. 6 — частная жалоба на определение суда кассационной инстанции
//     (PRIVATE_COMPLAINT_CASSATION_APK). Та же механика, что у ч. 3 и ч. 4.
//   ч. 5 — жалоба на постановление апелляции по жалобе на определение
//     (PRIVATE_COMPLAINT_APPELLATE_POSTANOVLENIE_APK). Якорь — день вступления
//     в силу такого постановления, но по факту равен дате его принятия
//     (ч. 5 ст. 271 АПК РФ) — отдельного узла "вступление в силу" не нужно.
// ст. 259 — сроки:
//   ч. 1 — общий месячный срок подачи жалобы (APPEAL_GENERAL_APK);
//   ч. 2 — предельный срок подачи ходатайства о восстановлении пропущенного
//     срока (APPEAL_GENERAL_APK_RESTORATION). Восстановление здесь — отдельный
//     вычисляемый узел, а не текстовая подсказка restoration_norm на узле ч. 1:
//     у трёх категорий субъектов разные точки отсчёта.
// ст. 180 — не срок:
//   ч. 1 — вступление решения в законную силу (ENTRY_INTO_FORCE_APK). Момент
//     смены статуса решения, а не срок для совершения действия, поэтому узел
//     устроен принципиально иначе остальных — см. комментарий к нему.
// ст. 276 — сроки:
//   ч. 1 — общий срок подачи кассационной жалобы (CASSATION_GENERAL_APK). Два
//     месяца со дня вступления в силу; якорь берётся из entry_into_force_apk
//     без дополнительной логики — см. комментарий к узлу.
//   ч. 2 — предельный срок подачи ходатайства о восстановлении пропущенного
//     срока (CASSATION_GENERAL_APK_RESTORATION). Тот же паттерн трёх категорий
//     субъектов, что и у APPEAL_GENERAL_APK_RESTORATION, с одним отличием:
//     якорь категории participating_duly_notified — день вступления в силу
//     (через entry_into_force_apk), а не decision_full_text_date напрямую.
// ст. 291.2 — якорь и срок:
//   ч. 1 (якорь) — вступление в силу последнего обжалуемого акта после
//     окружной кассации (ENTRY_INTO_FORCE_AFTER_CASSATION_APK). Не срок, по
//     той же причине, что и ENTRY_INTO_FORCE_APK (ст. 180).
//   ч. 1 (срок) — общий срок подачи кассационной жалобы в Судебную коллегию
//     ВС РФ (CASSATION_VS_APK). Два месяца со дня вступления в силу; якорь
//     берётся из entry_into_force_after_cassation_apk без дополнительной
