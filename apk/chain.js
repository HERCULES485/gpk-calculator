//
// ч. 1 ст. 259 — общий месячный срок подачи жалобы (APPEAL_GENERAL_APK);
// ч. 2 ст. 259 — предельный срок подачи ходатайства о восстановлении
// пропущенного срока (APPEAL_GENERAL_APK_RESTORATION). Восстановление здесь —
