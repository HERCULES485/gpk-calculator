// узле ч. 1: у трёх категорий субъектов разные точки отсчёта.
// Регистрация узлов в UI-реестре ситуаций и в .ics-реестре — отдельная
// задача (нет поля ics — оно сейчас нерабочее, ни один реестр apk/ не сканирует
// экспорты этого модуля).
//
// Домен АПК не переиспользует ГПК-поле reasoned_decision_date — имя входного
// поля должно однозначно указывать на АПК-семантику.

