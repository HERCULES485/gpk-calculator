// --- П. 6 ст. 61.14: заявление после завершения конкурсного производства -------
//
// Два кумулятивных потолка: три года со дня завершения конкурсного
// производства и не позднее десяти лет со дня действий (бездействия).
//
// Дата знания об основаниях здесь НЕ якорь (в отличие от п. 5), а условие
// применимости самого пункта: он действует, если лицо узнало об основаниях
// ПОСЛЕ завершения конкурсного производства. Расчётом это не выводится —
// какой пункт применим к его случаю, решает пользователь, выбирая узел:
// «узнал или должен был узнать» — оценочная категория, и момент, который
// признает суд, не обязан совпадать с введённой датой.
//
// ВНЕ ОБЪЁМА: условие «если аналогичное требование по тем же основаниям и к
// тем же лицам не было предъявлено и рассмотрено в деле о банкротстве».
// Это условие допустимости обращения, а не срок с фиксированной
// длительностью — считать в нём нечего, и установление факта «рассматривалось
// ли уже такое требование» лежит за пределами калькулятора дат (тот же
// случай, что абз. 2 ч. 2 ст. 222.1 АПК). В расчёт не входит, но в тексте
// нормы существует — поэтому упомянуто в logic ниже.
//
// Поле даты завершения конкурсного производства — своё
// (bankruptcy_proceeding_conclusion_date_apk), НЕ
// bankruptcy_declaration_notice_published_date_apk узла ст. 142 п. 1: там дата
// ПУБЛИКАЦИИ сведений об открытии конкурсного производства, здесь — дата его
