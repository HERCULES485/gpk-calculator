  if (knew == null) {
    throw new Error(
      'Обязательна дата, когда лицо, впоследствии утверждённое внешним или ' +
        'конкурсным управляющим, узнало или должно было узнать о наличии ' +
        'оснований для оспаривания сделки ' +
        '(transaction_challenge_manager_knew_date_apk)',
    );
  }

