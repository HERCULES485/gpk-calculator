/**
 * Срок подачи заявления о привлечении к субсидиарной ответственности после
 * завершения конкурсного производства (п. 6 ст. 61.14 ФЗ № 127-ФЗ). Минимум
 * из двух кумулятивных потолков.
 * @param {{
 *   bankruptcy_proceeding_conclusion_date_apk: string,
 *   subsidiary_liability_conduct_date_apk: string,
 * }} inputs
 */
export function computeSubsidiaryLiabilityPostConclusionApk(inputs) {
  const node = SUBSIDIARY_LIABILITY_POST_CONCLUSION_APK;

  const conclusion = inputs?.bankruptcy_proceeding_conclusion_date_apk;
  if (conclusion == null) {
    throw new Error(
      'Обязательна дата завершения конкурсного производства ' +
        '(bankruptcy_proceeding_conclusion_date_apk)',
    );
  }

  const conduct = inputs.subsidiary_liability_conduct_date_apk;
  if (conduct == null) {
    throw new Error(
      'Обязательна дата действий (бездействия), являющихся основанием для ' +
        'привлечения к ответственности (subsidiary_liability_conduct_date_apk)',
    );
  }

  const { deadline, caps, binding } = cappedTerm(node, {
    post_conclusion: conclusion,
    absolute: conduct,
  });

  return {
    id: node.id,
    kind: 'capped_term',
    norm: node.norm_versions[0].norm,
    logic: node.logic,
    midnight_rule: node.midnight_rule,
    deadline,
    caps,
    binding,
    anchors: {
      bankruptcy_proceeding_conclusion_date_apk: conclusion,
      subsidiary_liability_conduct_date_apk: conduct,
    },
  };
}

