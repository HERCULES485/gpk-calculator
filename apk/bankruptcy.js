// заявление.
//
// duration.unit: 'working_day', не 'day' и не календарные дни: в тексте нет
// оговорки "календарных" (в отличие от других мест того же закона, где она
// прямо есть — например, "тридцать календарных дней" в ст. 100 ФЗ № 127-ФЗ),
// значит действует общее правило ч. 3 ст. 113 АПК (нерабочие дни не
// включаются в счёт). Механика уже многократно проверена в apk/chain.js (13
// узлов ГПК-домена и пять working_day-узлов АПК-домена) — здесь перенос той
// же механики в новый домен, не новый код.
//
// Якорь — простое поле ввода creditor_petition_acceptance_ruling_received_date_apk
// (дата получения должником определения о принятии заявления), без
// дискриминаторов и без графа: норма самодостаточна, якорь однозначен.
//
// БЕЗ restoration: в этом фрагменте нормы последствия пропуска срока вообще
// не упоминаются — не тот случай "восстановление без числового потолка"
// (ст. 322, 112, 222.1 ч. 2, 229 ч. 4, 198 ч. 4, 208 ч. 2 АПК), а полное
// отсутствие в тексте самого института восстановления применительно к этому
// сроку (тот же случай, что и ч. 4 ст. 206 / ч. 5 ст. 211 АПК).

