/**
 * Срок направления должником отзыва на заявление кредитора/уполномоченного
 * органа о банкротстве (ст. 47 п. 1 ФЗ № 127-ФЗ). Десять рабочих дней с даты
 * получения должником определения о принятии заявления.
 * @param {{ creditor_petition_acceptance_ruling_received_date_apk: string }} inputs
 */
export function computeDebtorResponseBankruptcyApk(inputs) {
  const anchor = inputs?.creditor_petition_acceptance_ruling_received_date_apk;
  if (anchor == null) {
    throw new Error(
      'Обязательна дата получения должником определения о принятии заявления ' +
        'кредитора/уполномоченного органа о банкротстве ' +
        '(creditor_petition_acceptance_ruling_received_date_apk)',
    );
  }
  return computeSimpleTerm(DEBTOR_RESPONSE_BANKRUPTCY_APK, anchor);
}

