/**
 * Срок предъявления кредиторами требований к должнику для целей участия в
 * первом собрании кредиторов (ст. 71 п. 1 ФЗ № 127-ФЗ). Тридцать КАЛЕНДАРНЫХ
 * дней с даты опубликования сообщения о введении наблюдения; нерабочие дни
 * входят в счёт, переносится только итоговая дата.
 * @param {{ observation_introduction_notice_published_date_apk: string }} inputs
 */
export function computeCreditorClaimsSubmissionApk(inputs) {
  const anchor = inputs?.observation_introduction_notice_published_date_apk;
  if (anchor == null) {
    throw new Error(
      'Обязательна дата опубликования сообщения о введении наблюдения ' +
        '(observation_introduction_notice_published_date_apk)',
    );
  }
  return computeSimpleTerm(CREDITOR_CLAIMS_SUBMISSION_APK, anchor);
}
