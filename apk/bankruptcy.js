// --- Субсидиарная ответственность: срок подачи заявления (ст. 61.14 ФЗ № 127-ФЗ)
// ------------------------------------------------------------------------------
//
// ПЕРВЫЕ узлы проекта с формой результата «минимум из нескольких кумулятивных
// потолков» (kind: 'capped_term'). Отличие от узла-окна ч. 3 ст. 222.1
// (apk/chain.js): там две ИМЕНОВАННЫЕ границы одного диапазона (не ранее / не
// позднее), здесь — несколько верхних пределов ОДНОГО И ТОГО ЖЕ права, каждый
// из которых должен соблюдаться одновременно; итоговый дедлайн — самый ранний
// из них.
//
// П. 5 и п. 6 сделаны ДВУМЯ отдельными узлами, а не одним с дискриминатором:
// у них разный состав потолков (три против двух) и разная роль даты знания —
// в п. 5 это ЯКОРЬ (от неё считается трёхлетний срок), в п. 6 лишь условие
// применимости самого пункта («если лицо узнало ПОСЛЕ завершения конкурсного
// производства»), а якорем служит дата завершения производства. Тот же
// критерий «другой состав якорей → отдельный узел, а не ветка дискриминатора»,
// по которому ENFORCEMENT_PRESENTATION_AFTER_RESTORATION_APK не стал четвёртой
// веткой case_type у ENFORCEMENT_PRESENTATION_APK.
//
// ПОРЯДОК «СНАЧАЛА МИНИМУМ, ПОТОМ ПЕРЕНОС» — не косметика, обоснование ниже.
// Потолки сравниваются по СЫРЫМ датам (raw_deadline, до переноса), и перенос
// через нерабочий день (ч. 4 ст. 114 АПК РФ) применяется один раз — к тому
// потолку, который оказался минимальным.
//
// На сам ДЕДЛАЙН порядок не влияет: shiftIfNonWorking возвращает наименьший
// рабочий день не раньше аргумента, то есть монотонно неубывающая функция, а
// для такой функции min(shift(a), shift(b)) === shift(min(a, b)) — итог
// совпадает при любом порядке.
//
// А вот на BINDING влияет, и краевой случай реален (проверен на календаре):
// потолок A даёт сырую 05.04.2025 (суббота), потолок B — 06.04.2025
// (воскресенье); оба переносятся на 07.04.2025. Сравнение ПО ПЕРЕНЕСЁННЫМ
// датам объявило бы ничью и записало в binding оба потолка, хотя юридически
// срок ограничил именно A — он истекает раньше. Сравнение по сырым датам даёт
// binding: ['A'], что и соответствует норме. Поэтому сравнение — до переноса.
//
// По той же причине в caps результата лежат СЫРЫЕ даты: отдельный потолок сам
// по себе не является «последним днём процессуального срока» (ч. 4 ст. 114
// говорит именно о последнем дне срока), последним днём становится только
// минимум из них — он один и переносится.

// Общая механика обоих узлов-потолков: каждый потолок считается тем же
// computeSimpleTerm, что и все обычные сроки (параметры берутся из node.caps),
// сравнение идёт по raw_deadline, итоговым дедлайном становится уже
// перенесённый deadline минимального потолка. Отдельной арифметики нет.
function cappedTerm(node, anchorsByCap) {
  const caps = {};
  let minRaw = null;
  let deadline = null;
  for (const [capId, anchorDate] of Object.entries(anchorsByCap)) {
    const term = computeSimpleTerm({ ...node, ...node.caps[capId] }, anchorDate);
    caps[capId] = term.raw_deadline;
    if (minRaw == null || term.raw_deadline < minRaw) {
      minRaw = term.raw_deadline;
      deadline = term.deadline;
    }
  }
  // binding — массив, а не строка: потолки могут совпасть по дате, и выбирать
  // из равных один произвольно значило бы соврать о причине ограничения.
  const binding = Object.keys(caps).filter((capId) => caps[capId] === minRaw);
  return { deadline, caps, binding };
}

