// Узлы домена банкротства — ФЗ от 26.10.2002 № 127-ФЗ "О несостоятельности
// (банкротстве)". Первый файл этого домена, отдельный от apk/chain.js:
// банкротство — самостоятельный правовой институт (закон, а не кодекс), со
// своим корпусом узлов, которому предстоит расти независимо от
// процессуальной цепочки АПК. Смешивать с apk/chain.js не стали намеренно —
// тот файл описывает нормы АПК напрямую, этот — нормы закона о банкротстве,
// который лишь ОТСЫЛАЕТ к АПК как к процессуальной основе (ст. 223 АПК РФ:
// "дела о несостоятельности (банкротстве) рассматриваются арбитражным судом
// по правилам, предусмотренным настоящим Кодексом, с особенностями,
// установленными федеральными законами").
//
// Именно поэтому общая механика working_day (ч. 3, 4 ст. 113 АПК — нерабочие
// дни не включаются в счёт дневного срока; ч. 4 ст. 114 — перенос последнего
// дня месячного/годового срока) применяется здесь как обычно, без отдельного
// движка: расчёт использует тот же core/engine/term.js, что и apk/chain.js.
// Норм-цитаты при этом — на закон ('ФЗ № 127-ФЗ'), а не на 'АПК РФ': сама
// обязанность и её срок установлены законом о банкротстве, АПК даёт только
// процессуальный механизм исчисления.
//
// UI-подключение (apk/situations.js, apk/labels.js, apk/views.js, apk.html,
// apk/app.js) — НЕ ЗДЕСЬ и не в этой задаче. Пока в домене банкротства один
// узел, рано решать архитектуру его интерфейса (отдельная ветвь переключателя,
// часть общей АПК-формы или что-то третье) — то же соображение, по которому
// сначала копился весь модуль apk/, а UI подключался отдельным шагом уже
// после того, как состав графа стал ясен на нескольких узлах.

import { computeSimpleTerm } from '../core/engine/term.js';

// --- Отзыв должника на заявление о банкротстве (ст. 47 п. 1 ФЗ № 127-ФЗ) -----
//
// В течение десяти дней с даты получения определения о принятии заявления
// кредитора/уполномоченного органа должник обязан направить отзыв на такое
// заявление.
//
// duration.unit: 'working_day', не 'day' и не календарные дни: в тексте нет
// оговорки "календарных" (в отличие от других мест того же закона, где она
// прямо есть — например, "тридцать календарных дней" в ст. 100 ФЗ № 127-ФЗ),
// значит действует общее правило ч. 3 ст. 113 АПК (нерабочие дни не
// включаются в счёт). Механика уже многократно проверена в apk/chain.js (13
// узлов ГПК-домена и пять working_day-узлов АПК-домена) — здесь перенос той
// же механики в новый домен, не новый код.
//
// Якорь — простое поле ввода creditor_petition_acceptance_ruling_received_date_apk
// (дата получения должником определения о принятии заявления), без
// дискриминаторов и без графа: норма самодостаточна, якорь однозначен.
//
// БЕЗ restoration: в этом фрагменте нормы последствия пропуска срока вообще
// не упоминаются — не тот случай "восстановление без числового потолка"
// (ст. 322, 112, 222.1 ч. 2, 229 ч. 4, 198 ч. 4, 208 ч. 2 АПК), а полное
// отсутствие в тексте самого института восстановления применительно к этому
// сроку (тот же случай, что и ч. 4 ст. 206 / ч. 5 ст. 211 АПК).

export const DEBTOR_RESPONSE_BANKRUPTCY_APK = {
  id: 'debtor_response_bankruptcy_apk',
  title: 'Отзыв должника на заявление о банкротстве',
  duration: { value: 10, unit: 'working_day' },
  anchor: { offset_start: 1 },
  logic:
    'Десять дней с даты получения должником определения о принятии заявления ' +
    'кредитора или уполномоченного органа (ст. 47 п. 1 ФЗ № 127-ФЗ). Срок ' +
    'исчисляется днями — нерабочие дни не включаются (ч. 3 ст. 113 АПК РФ, ' +
    'применяется через ст. 223 АПК РФ); течение начинается со дня, следующего ' +
    'за получением определения.',
  midnight_rule:
    'ч. 5, 6 ст. 114 АПК РФ — процессуальное действие может быть совершено, а ' +
    'отзыв сдан на почту, до 24:00 последнего дня срока.',
  norm_versions: [
    {
      id: 'current',
      from: null,
      to: null,
      anchor: { offset_start: 1 },
      norm: {
        primary: 'ст. 47 п. 1 ФЗ № 127-ФЗ',
        calculation: ['ч. 3 ст. 113 АПК РФ', 'ст. 223 АПК РФ'],
      },
    },
  ],
};

/**
 * Срок направления должником отзыва на заявление кредитора/уполномоченного
 * органа о банкротстве (ст. 47 п. 1 ФЗ № 127-ФЗ). Десять рабочих дней с даты
 * получения должником определения о принятии заявления.
 * @param {{ creditor_petition_acceptance_ruling_received_date_apk: string }} inputs
 */
export function computeDebtorResponseBankruptcyApk(inputs) {
  const anchor = inputs?.creditor_petition_acceptance_ruling_received_date_apk;
  if (anchor == null) {
    throw new Error(
      'Обязательна дата получения должником определения о принятии заявления ' +
        'кредитора/уполномоченного органа о банкротстве ' +
        '(creditor_petition_acceptance_ruling_received_date_apk)',
    );
  }
  return computeSimpleTerm(DEBTOR_RESPONSE_BANKRUPTCY_APK, anchor);
}
