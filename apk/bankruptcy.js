// Границы окна считаются тем же computeSimpleTerm, что и все обычные сроки:
// параметры длительности берутся из window.earliest/window.latest, а id,
// title, норма и тексты — из самого узла. Ровно тот же приём, что у
// windowBoundary в apk/chain.js и у cappedTerm выше в этом файле.
function settlementWindowBoundary(side, anchorDate) {
  const node = SETTLEMENT_AGREEMENT_APPROVAL_APPLICATION_APK;
  return computeSimpleTerm({ ...node, ...node.window[side] }, anchorDate);
}

/**
 * Окно подачи заявления об утверждении мирового соглашения (п. 2 ст. 158 ФЗ
 * № 127-ФЗ): не ранее пяти и не позднее десяти рабочих дней с даты заключения
 * мирового соглашения. Обе границы определены всегда — состояний «окно
 * открыто сверху» или «окно пустое» у этого узла не бывает.
 * @param {{ settlement_agreement_conclusion_date_apk: string }} inputs
 */
export function computeSettlementAgreementApprovalApplicationApk(inputs) {
  const node = SETTLEMENT_AGREEMENT_APPROVAL_APPLICATION_APK;
  const anchor = inputs?.settlement_agreement_conclusion_date_apk;
  if (anchor == null) {
    throw new Error(
      'Обязательна дата заключения мирового соглашения ' +
        '(settlement_agreement_conclusion_date_apk)',
    );
  }

  const earliest = settlementWindowBoundary('earliest', anchor);
  const latest = settlementWindowBoundary('latest', anchor);

  return {
    id: node.id,
    norm: node.norm_versions[0].norm,
    logic: node.logic,
    midnight_rule: node.midnight_rule,
    earliest_filing_date: earliest.deadline,
    latest_filing_date: latest.deadline,
    // Первый рабочий день течения — общий у обеих границ (якорь и offset_start
    // у них одни и те же). Без него непонятно, почему окно уехало далеко
    // вперёд, если сразу за датой заключения идут праздничные дни.
    first_working_day: earliest.first_working_day,
    anchors: { settlement_agreement_conclusion_date_apk: anchor },
  };
}

