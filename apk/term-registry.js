// Реестр сроков АПК и предметные параметры экспорта в календарь.
//
// Тот же принцип, что у src/term-registry.js: реестр собирается исчерпывающим
// `import * as chainModule` — новый узел попадает в него вместе с самим
// определением срока, отдельным списком его регистрировать не нужно и молча
// выпасть из экспорта он не может.
//
// ОТЛИЧИЕ ОТ ГПК: у ГПК признак экспортируемости — поле `ics` на самом узле, и
// фильтр ядра по умолчанию требует его наличия. Узлы АПК такого поля не несут, и
// добавлять его в apk/chain.js ради экспорта не стали — предметный модуль
// описывает нормы, а не то, что интерфейс кладёт в календарь. Поэтому здесь
// передаётся свой предикат отбора (options.filter, см. buildTermRegistry), а
// признак `ics: true` навешивается на запись реестра при раскладке по id.
// Навесить его необходимо: exportableCards в ядре отбирает карточки по
// meta.ics === true, одного лишь фильтра реестра ему мало.
//
// Отбор: экспортируемы все узлы со сроком, то есть 12 из 14. Не экспортируются
// entry_into_force_apk и entry_into_force_after_cassation_apk — это узлы-события
// (момент вступления акта в силу), у них нет ни duration, ни дедлайна:
// напоминать не о чем.

import { buildTermRegistry } from '../core/export/ics.js';

import * as chainModule from './chain.js';

// Предикат отбора: объект со строковым id и непустым duration. Каталоги
// оснований (массивы), Set-ы идентификаторов и compute-функции ему не
// удовлетворяют и в реестр не попадают.
const isTermNode = (v) =>
  v != null && typeof v === 'object' && typeof v.id === 'string' && Boolean(v.duration);

/**
 * Реестр сроков АПК по id узла. Потребители (exportableCards, apk/app.js) ищут
 * метаданные узла по id карточки.
 */
export const TERM_REGISTRY_APK = Object.fromEntries(
  buildTermRegistry(chainModule, { filter: isTermNode }).map((term) => [
    term.id,
    { ...term, ics: true },
  ]),
);

// Идентификаторы продукта в теле .ics: PRODID календаря и доменный суффикс UID
// после «@». Ядро их не подставляет (см. buildICS) — передаём явно отсюда.
//
// UID-домен отличается от ГПК-шного ('gpk-calculator'): UID собирается как
// дата-индекс-токен@домен, и в календаре, куда выгружены сроки обоих модулей,
// одинаковый суффикс стирал бы границу между ними при разборе конфликтов.
export const ICS_PRODID = '-//gpk-calculator//Процессуальные сроки АПК//RU';
export const ICS_UID_DOMAIN = 'apk-calculator';

// Правила напоминаний по длительности срока: смещения до дедлайна, не больше
// двух на событие (календари обрезают список молча и отбрасывают именно
// последние — ближайшие к дедлайну и самые нужные). Поэтому смещения
// перечислены от ближайшего к дедлайну к более раннему.
//
// Принцип таблицы перенесён из ГПК (src/term-registry.js): ближнее напоминание
// не растёт вместе со сроком, дальнее — растёт. Значения для 1, 3, 6 месяцев и
// 3 лет совпадают с ГПК-шными дословно: те же длительности, тот же принцип.
//
// Двухмесячного срока (ст. 276 ч. 1, ст. 291.2 ч. 1) у ГПК нет, и из принципа
// выводится только коридор между значениями для одного и трёх месяцев — сами
// числа 7/14/30 не формула, а подобранные значения. 10 дней здесь — решение по
// месту в этом коридоре, а не расчёт.
//
// Сроков, исчисляемых рабочими днями, в модуле АПК нет ни одного — ветки для
// working_day в таблице нет; для длительности, которой в таблице нет,
// возвращается пустой список (срок остаётся без напоминаний, само событие в
// файле при этом есть).
export function reminderOffsets(duration) {
  if (duration && duration.unit === 'month' && duration.value === 1) {
    return [
      { unit: 'day', value: 3 },
      { unit: 'day', value: 7 },
    ];
  }
  if (duration && duration.unit === 'month' && duration.value === 2) {
    return [
      { unit: 'day', value: 3 },
      { unit: 'day', value: 10 },
    ];
  }
  if (duration && duration.unit === 'month' && duration.value === 3) {
    return [
      { unit: 'day', value: 3 },
      { unit: 'day', value: 14 },
    ];
  }
  if (duration && duration.unit === 'month' && duration.value === 6) {
    return [
      { unit: 'day', value: 3 },
      { unit: 'day', value: 30 },
    ];
  }
  if (duration && duration.unit === 'year' && duration.value === 3) {
    return [
      { unit: 'day', value: 7 },
      { unit: 'month', value: 1 },
    ];
  }
  return [];
}
